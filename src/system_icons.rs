//! Module 6 - cross-platform file association and custom icons.
//!
//! `hermes install-system` teaches the desktop what a `.origin` and a `.foiled`
//! file are, gives them icons, and points double-clicks at this binary. Every
//! icon is compiled into the executable with `include_bytes!` and written out
//! at install time, so there is no installer, no asset directory to ship and
//! nothing to go missing after the binary is moved.
//!
//! All three platforms register **per-user**:
//!
//! * Windows - `HKEY_CURRENT_USER\Software\Classes` (no elevation).
//! * Linux   - `~/.local/share/{mime,applications,icons}` (FreeDesktop).
//! * macOS   - `~/Applications/Hermes.app` with `CFBundleDocumentTypes`.
//!
//! Nothing is written outside the user's own profile, and `uninstall-system`
//! reverses all of it.

use crate::paths;
use anyhow::{Context, Result};
use std::fs;
use std::path::{Path, PathBuf};

pub const PROGID_ORIGIN: &str = "Hermes.Origin";
pub const PROGID_FOILED: &str = "Hermes.Foiled";
// The MIME types and UTIs are the public naming contract for the type; each is
// referenced only by the platform module that speaks that dialect.
#[allow(dead_code)]
pub const MIME_ORIGIN: &str = "application/x-hermes-origin";
#[allow(dead_code)]
pub const MIME_FOILED: &str = "application/x-hermes-foiled";
#[allow(dead_code)]
pub const UTI_ORIGIN: &str = "dev.hermes.origin";
#[allow(dead_code)]
pub const UTI_FOILED: &str = "dev.hermes.foiled";
pub const DESC_ORIGIN: &str = "HERMES Origin (software source)";
pub const DESC_FOILED: &str = "HERMES Update Plan";

