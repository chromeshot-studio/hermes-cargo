#[cfg(windows)]
mod platform {
    use super::*;
    use winreg::enums::{HKEY_CURRENT_USER, KEY_ALL_ACCESS};
    use winreg::RegKey;

    const CLASSES: &str = r"Software\Classes";

    /// Tell Explorer the association table changed, so icons refresh without
    /// a logout. Declared directly to avoid pulling in a Win32 crate.
    fn notify_assoc_changed() {
        const SHCNE_ASSOCCHANGED: i32 = 0x0800_0000;
        const SHCNF_IDLIST: u32 = 0x0000;
        #[link(name = "shell32")]
        extern "system" {
            fn SHChangeNotify(
                event_id: i32,
                flags: u32,
                item1: *const std::ffi::c_void,
                item2: *const std::ffi::c_void,
            );
        }
        unsafe {
            SHChangeNotify(
                SHCNE_ASSOCCHANGED,
                SHCNF_IDLIST,
                std::ptr::null(),
                std::ptr::null(),
            );
        }
    }

    fn register_progid(
        classes: &RegKey,
        progid: &str,
        description: &str,
        icon: &Path,
        command: &str,
        report: &mut Report,
    ) -> Result<()> {
        let (key, _) = classes
            .create_subkey(progid)
            .with_context(|| format!(r"creating HKCU\{CLASSES}\{progid}"))?;
        key.set_value("", &description)?;
        key.set_value("FriendlyTypeName", &description)?;
        // Explorer refuses to show a custom icon for a type it thinks is
        // "always show extension"-less; this keeps the extension visible.
        key.set_value("AlwaysShowExt", &"")?;

        let (icon_key, _) = key.create_subkey("DefaultIcon")?;
        icon_key.set_value("", &format!("\"{}\",0", icon.display()))?;

        let (command_key, _) = key.create_subkey(r"shell\open\command")?;
        command_key.set_value("", &command.to_string())?;

        let (verb_key, _) = key.create_subkey(r"shell\open")?;
        verb_key.set_value("FriendlyAppName", &"HERMES")?;

        report.did(format!(r"HKCU\{CLASSES}\{progid} -> {command}"));
        Ok(())
    }

    fn associate_extension(
        classes: &RegKey,
        extension: &str,
        progid: &str,
        report: &mut Report,
    ) -> Result<()> {
        let (key, _) = classes
            .create_subkey(extension)
            .with_context(|| format!(r"creating HKCU\{CLASSES}\{extension}"))?;
        key.set_value("", &progid)?;
        // OpenWithProgids keeps HERMES in the "Open with" list even if another
        // application later claims the default.
        let (open_with, _) = key.create_subkey("OpenWithProgids")?;
        open_with.set_value(progid, &"")?;
        report.did(format!(r"HKCU\{CLASSES}\{extension} -> {progid}"));
        Ok(())
    }

    /// The registration itself, against whichever classes key it is handed.
    /// Taking the root as a parameter keeps this exercisable by tests without
    /// touching the user's real file associations.
    fn register_all(classes: &RegKey, exe: &Path, icons: &Path, report: &mut Report) -> Result<()> {
        // `open` dispatches on the extension: a .origin is registered, a
        // .foiled is inspected. --from-shell keeps the console window up so a
        // double-click is readable.
        let command = format!("\"{}\" open \"%1\" --from-shell", exe.display());

        register_progid(
            classes,
            PROGID_ORIGIN,
            DESC_ORIGIN,
            &icons.join("origin.ico"),
            &command,
            report,
        )?;
        register_progid(
            classes,
            PROGID_FOILED,
            DESC_FOILED,
            &icons.join("foiled.ico"),
            &command,
            report,
        )?;
        associate_extension(classes, ".origin", PROGID_ORIGIN, report)?;
        associate_extension(classes, ".foiled", PROGID_FOILED, report)?;
        Ok(())
    }

    pub fn install(exe: &Path, icons: &Path, report: &mut Report) -> Result<()> {
        let hkcu = RegKey::predef(HKEY_CURRENT_USER);
        let (classes, _) = hkcu
            .create_subkey_with_flags(CLASSES, KEY_ALL_ACCESS)
            .context("opening HKCU\\Software\\Classes for writing")?;

        register_all(&classes, exe, icons, report)?;

        notify_assoc_changed();
        report.did("notified Explorer (SHChangeNotify)".to_string());
        Ok(())
    }

    pub fn uninstall(report: &mut Report) -> Result<()> {
        let hkcu = RegKey::predef(HKEY_CURRENT_USER);
        let classes = match hkcu.open_subkey_with_flags(CLASSES, KEY_ALL_ACCESS) {
            Ok(k) => k,
            Err(_) => return Ok(()),
        };

        for progid in [PROGID_ORIGIN, PROGID_FOILED] {
            if classes.delete_subkey_all(progid).is_ok() {
                report.did(format!(r"removed HKCU\{CLASSES}\{progid}"));
            }
        }

        for (extension, progid) in [(".origin", PROGID_ORIGIN), (".foiled", PROGID_FOILED)] {
            if let Ok(key) = classes.open_subkey_with_flags(extension, KEY_ALL_ACCESS) {
                // Only stand down if we are still the default handler.
                let current: std::result::Result<String, _> = key.get_value("");
                if matches!(current.as_deref(), Ok(value) if value == progid) {
                    let _ = key.set_value("", &"");
                }
                if let Ok(open_with) = key.open_subkey_with_flags("OpenWithProgids", KEY_ALL_ACCESS)
                {
                    let _ = open_with.delete_value(progid);
                }
                report.did(format!(r"released HKCU\{CLASSES}\{extension}"));
            }
        }

        notify_assoc_changed();
        Ok(())
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        /// Run the real registration against a scratch key, assert the shape
        /// Explorer needs, then remove it. Never touches Software\Classes.
        #[test]
        fn registers_progids_icons_and_commands() {
            const SCRATCH: &str = r"Software\Hermes.SelfTest";
            let hkcu = RegKey::predef(HKEY_CURRENT_USER);
            let _ = hkcu.delete_subkey_all(SCRATCH);
            let (classes, _) = hkcu
                .create_subkey_with_flags(SCRATCH, KEY_ALL_ACCESS)
                .expect("create scratch key");

            let exe = Path::new(r"C:\Program Files\Hermes\hermes.exe");
            let icons = Path::new(r"C:\Users\test\.config\hermes\icons");
            let mut report = Report::default();
            register_all(&classes, exe, icons, &mut report).expect("registration");

            let progid = classes.open_subkey(PROGID_ORIGIN).expect("progid key");
            let description: String = progid.get_value("").expect("progid default value");
            assert_eq!(description, DESC_ORIGIN);

            let icon: String = progid
                .open_subkey("DefaultIcon")
                .expect("DefaultIcon key")
                .get_value("")
                .expect("icon value");
            assert!(icon.ends_with(r#"origin.ico",0"#), "unexpected icon: {icon}");

            let command: String = progid
                .open_subkey(r"shell\open\command")
                .expect("command key")
                .get_value("")
                .expect("command value");
            assert!(command.contains("hermes.exe"), "unexpected command: {command}");
            assert!(command.contains(" open "), "unexpected command: {command}");
            assert!(command.ends_with(r#""%1" --from-shell"#), "unexpected command: {command}");

            for (extension, expected) in [(".origin", PROGID_ORIGIN), (".foiled", PROGID_FOILED)] {
                let key = classes.open_subkey(extension).expect("extension key");
                let mapped: String = key.get_value("").expect("extension default value");
                assert_eq!(mapped, expected);
                key.open_subkey("OpenWithProgids")
                    .expect("OpenWithProgids")
                    .get_value::<String, _>(expected)
                    .expect("listed in OpenWithProgids");
            }

            hkcu.delete_subkey_all(SCRATCH).expect("clean up scratch key");
            assert!(hkcu.open_subkey(SCRATCH).is_err());
        }

        /// Regression: `canonicalize` hands back `\\?\D:\...`, and a verbatim
        /// path in shell\open\command makes a double-click do nothing at all.
        #[test]
        fn registered_command_never_contains_a_verbatim_path() {
            assert_eq!(
                strip_verbatim(PathBuf::from(r"\\?\D:\Tools\hermes.exe")),
                PathBuf::from(r"D:\Tools\hermes.exe")
            );
            assert_eq!(
                strip_verbatim(PathBuf::from(r"\\?\UNC\server\share\hermes.exe")),
                PathBuf::from(r"\\server\share\hermes.exe")
            );
            // Ordinary paths are left exactly as they are.
            assert_eq!(
                strip_verbatim(PathBuf::from(r"C:\Program Files\Hermes\hermes.exe")),
                PathBuf::from(r"C:\Program Files\Hermes\hermes.exe")
            );
            assert!(!current_exe()
                .expect("current exe")
                .to_string_lossy()
                .starts_with(r"\\?\"));
        }
    }
}

