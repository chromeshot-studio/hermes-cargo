#[cfg(target_os = "linux")]
mod platform {
    use super::*;
    use std::process::Command;

    fn data_home() -> Result<PathBuf> {
        if let Some(dir) = std::env::var_os("XDG_DATA_HOME").filter(|v| !v.is_empty()) {
            return Ok(PathBuf::from(dir));
        }
        Ok(dirs::home_dir()
            .context("cannot determine the home directory")?
            .join(".local")
            .join("share"))
    }

    fn mime_xml() -> String {
        format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">
  <mime-type type="{MIME_ORIGIN}">
    <comment>{DESC_ORIGIN}</comment>
    <icon name="application-x-hermes-origin"/>
    <glob pattern="*.origin"/>
    <sub-class-of type="application/json"/>
  </mime-type>
  <mime-type type="{MIME_FOILED}">
    <comment>{DESC_FOILED}</comment>
    <icon name="application-x-hermes-foiled"/>
    <glob pattern="*.foiled"/>
    <sub-class-of type="application/json"/>
  </mime-type>
</mime-info>
"#
        )
    }

    fn desktop_entry(exe: &Path) -> String {
        format!(
            "[Desktop Entry]\n\
             Type=Application\n\
             Name=HERMES\n\
             GenericName=Decentralized Updater\n\
             Comment=Add and update software from a studio you trust\n\
             Exec={} open %f --from-shell\n\
             Icon=hermes\n\
             Terminal=true\n\
             Categories=System;PackageManager;Utility;\n\
             MimeType={MIME_ORIGIN};{MIME_FOILED};\n\
             NoDisplay=false\n\
             StartupNotify=false\n",
            exe.display()
        )
    }

    /// Install one icon into every hicolor size the theme spec expects.
    ///
    /// The artwork is raster, so there is no `scalable/` SVG to install; a
    /// 256px PNG is what every current desktop actually picks up.
    fn install_icon_set(
        data: &Path,
        theme_name: &str,
        context: &str,
        pngs: &[(u32, &[u8])],
        report: &mut Report,
    ) -> Result<()> {
        for (size, bytes) in pngs {
            let dir = data
                .join("icons/hicolor")
                .join(format!("{size}x{size}"))
                .join(context);
            fs::create_dir_all(&dir)?;
            fs::write(dir.join(format!("{theme_name}.png")), bytes)?;
        }
        report.did(format!("installed icon '{theme_name}' ({context})"));
        Ok(())
    }

    fn run_if_present(program: &str, args: &[&str], report: &mut Report) {
        match Command::new(program).args(args).status() {
            Ok(status) if status.success() => report.did(format!("ran {program}")),
            Ok(status) => report.warn(format!("{program} exited with {status}")),
            Err(_) => report.warn(format!(
                "{program} not found - log out and back in for the icons to appear"
            )),
        }
    }

    pub fn install(exe: &Path, _icons: &Path, report: &mut Report) -> Result<()> {
        let data = data_home()?;

        let mime_dir = data.join("mime/packages");
        fs::create_dir_all(&mime_dir)?;
        let mime_file = mime_dir.join("hermes.xml");
        fs::write(&mime_file, mime_xml())
            .with_context(|| format!("writing {}", mime_file.display()))?;
        report.did(format!("wrote {}", mime_file.display()));

        install_icon_set(
            &data,
            "application-x-hermes-origin",
            "mimetypes",
            embedded::ORIGIN_PNGS,
            report,
        )?;
        install_icon_set(
            &data,
            "application-x-hermes-foiled",
            "mimetypes",
            embedded::FOILED_PNGS,
            report,
        )?;
        install_icon_set(
            &data,
            "hermes",
            "apps",
            embedded::HERMES_PNGS,
            report,
        )?;

        let apps_dir = data.join("applications");
        fs::create_dir_all(&apps_dir)?;
        let desktop = apps_dir.join("hermes.desktop");
        fs::write(&desktop, desktop_entry(exe))
            .with_context(|| format!("writing {}", desktop.display()))?;
        report.did(format!("wrote {}", desktop.display()));

        run_if_present(
            "update-mime-database",
            &[data.join("mime").to_string_lossy().as_ref()],
            report,
        );
        run_if_present(
            "update-desktop-database",
            &[apps_dir.to_string_lossy().as_ref()],
            report,
        );
        run_if_present(
            "gtk-update-icon-cache",
            &[
                "-f",
                "-t",
                data.join("icons/hicolor").to_string_lossy().as_ref(),
            ],
            report,
        );
        Ok(())
    }

    pub fn uninstall(report: &mut Report) -> Result<()> {
        let data = data_home()?;
        let mut removed = Vec::new();

        for path in [
            data.join("mime/packages/hermes.xml"),
            data.join("applications/hermes.desktop"),
        ] {
            if fs::remove_file(&path).is_ok() {
                removed.push(path);
            }
        }

        for name in [
            "application-x-hermes-origin",
            "application-x-hermes-foiled",
            "hermes",
        ] {
            for size in [16, 22, 24, 32, 48, 64, 128, 256] {
                for context in ["mimetypes", "apps"] {
                    let p = data
                        .join("icons/hicolor")
                        .join(format!("{size}x{size}"))
                        .join(context)
                        .join(format!("{name}.png"));
                    let _ = fs::remove_file(p);
                }
            }
        }

        for path in removed {
            report.did(format!("removed {}", path.display()));
        }
        run_if_present(
            "update-mime-database",
            &[data.join("mime").to_string_lossy().as_ref()],
            report,
        );
        run_if_present(
            "update-desktop-database",
            &[data.join("applications").to_string_lossy().as_ref()],
            report,
        );
        Ok(())
    }
}

