/// Icons live in the binary. `assets/icons` is generated by
/// `tools/gen_icons.py` from the master artwork.
mod embedded {
    #[cfg(windows)]
    pub const ORIGIN_ICO: &[u8] = include_bytes!("../assets/icons/origin.ico");
    #[cfg(windows)]
    pub const FOILED_ICO: &[u8] = include_bytes!("../assets/icons/foiled.ico");
    #[cfg(windows)]
    pub const HERMES_ICO: &[u8] = include_bytes!("../assets/icons/hermes.ico");

    #[cfg(target_os = "macos")]
    pub const ORIGIN_ICNS: &[u8] = include_bytes!("../assets/icons/origin.icns");
    #[cfg(target_os = "macos")]
    pub const FOILED_ICNS: &[u8] = include_bytes!("../assets/icons/foiled.icns");
    #[cfg(target_os = "macos")]
    pub const HERMES_ICNS: &[u8] = include_bytes!("../assets/icons/hermes.icns");

    #[cfg(target_os = "linux")]
    macro_rules! png_set {
        ($name:literal) => {
            &[
                (16u32, include_bytes!(concat!("../assets/icons/", $name, "_16.png")) as &[u8]),
                (22u32, include_bytes!(concat!("../assets/icons/", $name, "_22.png")) as &[u8]),
                (24u32, include_bytes!(concat!("../assets/icons/", $name, "_24.png")) as &[u8]),
                (32u32, include_bytes!(concat!("../assets/icons/", $name, "_32.png")) as &[u8]),
                (48u32, include_bytes!(concat!("../assets/icons/", $name, "_48.png")) as &[u8]),
                (64u32, include_bytes!(concat!("../assets/icons/", $name, "_64.png")) as &[u8]),
                (128u32, include_bytes!(concat!("../assets/icons/", $name, "_128.png")) as &[u8]),
                (256u32, include_bytes!(concat!("../assets/icons/", $name, "_256.png")) as &[u8]),
            ]
        };
    }

    #[cfg(target_os = "linux")]
    pub const ORIGIN_PNGS: &[(u32, &[u8])] = png_set!("origin");
    #[cfg(target_os = "linux")]
    pub const FOILED_PNGS: &[(u32, &[u8])] = png_set!("foiled");
    #[cfg(target_os = "linux")]
    pub const HERMES_PNGS: &[(u32, &[u8])] = png_set!("hermes");

}

#[derive(Debug, Default)]
pub struct Report {
    pub actions: Vec<String>,
    pub warnings: Vec<String>,
}

impl Report {
    fn did(&mut self, what: impl Into<String>) {
        self.actions.push(what.into());
    }
    fn warn(&mut self, what: impl Into<String>) {
        self.warnings.push(what.into());
    }
    pub fn print(&self) {
        for action in &self.actions {
            println!("  + {action}");
        }
        for warning in &self.warnings {
            println!("  ! {warning}");
        }
    }
}

/// Absolute path to this binary, which is what the OS will be told to launch.
fn current_exe() -> Result<PathBuf> {
    let exe = std::env::current_exe().context("cannot determine this executable's path")?;
    let canonical = fs::canonicalize(&exe).unwrap_or_else(|_| exe.clone());
    Ok(strip_verbatim(canonical))
}

/// Undo the `\\?\` prefix that `canonicalize` adds on Windows.
///
/// It matters here and nowhere else: `ShellExecute` - which is what runs a
/// `shell\open\command` on a double-click - does not accept verbatim paths, so
/// registering one produces an association that silently does nothing.
fn strip_verbatim(path: PathBuf) -> PathBuf {
    let text = path.to_string_lossy().to_string();
    if let Some(rest) = text.strip_prefix(r"\\?\UNC\") {
        return PathBuf::from(format!(r"\\{rest}"));
    }
    if let Some(rest) = text.strip_prefix(r"\\?\") {
        // Only for real drive paths: \\?\C:\... -> C:\...
        let mut chars = rest.chars();
        if chars.next().is_some_and(|c| c.is_ascii_alphabetic())
            && chars.next() == Some(':')
            && chars.next() == Some('\\')
        {
            return PathBuf::from(rest);
        }
    }
    path
}

/// Warn if the binary lives somewhere the association will not survive.
fn check_exe_location(exe: &Path, report: &mut Report) {
    let text = exe.to_string_lossy().to_lowercase();
    let volatile = ["\\target\\", "/target/", "\\temp\\", "/tmp/", "\\appdata\\local\\temp\\"];
    if volatile.iter().any(|frag| text.contains(frag)) {
        report.warn(format!(
            "registering {} - this looks like a build or temp directory; \
             move HERMES somewhere permanent and re-run install-system",
            exe.display()
        ));
    }
}

/// Write the embedded icons into `~/.config/hermes/icons` and return the dir.
fn extract_icons() -> Result<PathBuf> {
    let dir = paths::icons_dir()?;
    #[cfg(windows)]
    {
        write_icon(&dir, "origin.ico", embedded::ORIGIN_ICO)?;
        write_icon(&dir, "foiled.ico", embedded::FOILED_ICO)?;
        write_icon(&dir, "hermes.ico", embedded::HERMES_ICO)?;
    }
    #[cfg(target_os = "macos")]
    {
        write_icon(&dir, "origin.icns", embedded::ORIGIN_ICNS)?;
        write_icon(&dir, "foiled.icns", embedded::FOILED_ICNS)?;
        write_icon(&dir, "hermes.icns", embedded::HERMES_ICNS)?;
    }
    #[cfg(target_os = "linux")]
    {
        // Linux reads its icons straight out of the hicolor theme, which
        // `platform::install` populates; nothing extra is needed here.
    }
    Ok(dir)
}

#[allow(dead_code)]
fn write_icon(dir: &Path, name: &str, bytes: &[u8]) -> Result<PathBuf> {
    let path = dir.join(name);
    fs::write(&path, bytes).with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

/// Register `.origin` and `.foiled` with the desktop.
///
/// `exe_override` lets `hermes install` register the copy it just placed in a
/// permanent directory rather than the binary currently running, which may be
/// sitting in `target/release` and about to be deleted by `cargo clean`.
pub fn install(exe_override: Option<PathBuf>) -> Result<Report> {
    let mut report = Report::default();
    let exe = match exe_override {
        Some(path) => path,
        None => current_exe()?,
    };
    check_exe_location(&exe, &mut report);
    let icons = extract_icons()?;
    report.did(format!("extracted icons to {}", icons.display()));
    platform::install(&exe, &icons, &mut report)?;
    Ok(report)
}

/// Undo everything `install` did.
pub fn uninstall() -> Result<Report> {
    let mut report = Report::default();
    platform::uninstall(&mut report)?;
    Ok(report)
}

